/**
 * 「阿瓦隆」的**代码级发言过滤** —— 说出口的话不许自带答案。
 *
 * ────────────────────────────────────────────────────────────────
 * ⚠️ 先说这条规则**怎么判**(这是本游戏最容易抄错的一处,用户点名要写清楚)
 *
 * 用户的问题原话:阿瓦隆里「我是梅林」这种**也可能是假的**,哪些该拦、哪些该放?
 *
 * 判断的**唯一标准**:这句话是「只有某个角色才说得出口的**事实**」,
 * 还是「任何人都能说的**声明**」?
 *
 *   ① **放行:任何身份声明** —— 「我是梅林」「我是派西维尔」「我是忠臣」。
 *      理由和狼人杀的「悍跳预言家」完全一样:这个游戏的**核心 bluff** 就是身份声明。
 *      好人会假跳梅林(派西维尔跳梅林挡刺杀、忠臣跳梅林钓鱼),
 *      坏人会假跳梅林(找真正的梅林、或者搅乱视线)。从文本上**无法区分**
 *      「我是梅林」是真是假 —— 而一旦把这句话拦掉,这个游戏最能看的部分
 *      (对跳、钓鱼、最后的刺杀博弈)就全没了。
 *
 *   ② **放行:「某号是梅林」这种指认** —— 阿瓦隆里**没有人**知道谁是梅林
 *      (坏人互相认识,但**不知道**梅林是谁;梅林知道坏人,但不知道别人怎么看他)。
 *      所以「3 号是梅林」永远只是一个猜测/钓鱼,不可能是泄题。
 *
 *   ③ **放行:「我怀疑 / 我认为 / 我觉得 3 号是坏人」** —— 这是推理,是牌桌上该说的话。
 *
 *   ④ **拦住:把私有知识说成事实** ——
 *      · 「我知道 / 我能确定 3 号是坏人」:只有梅林说得出这句话(忠臣没有信息,
 *        坏人靠猜),说出来等于自报「我知道坏人名单」,下一刀就是梅林;
 *      · 「我是坏人 / 我们是刺客 / 我的队友是 7 号」:自曝阵营(和狼人杀同一条);
 *      · 「我投了失败 / 我出了破坏票」:好人被规则钉死只能投成功,所以这句话
 *        只可能是坏人说的 —— 这是**规则保证的**自曝,不是修辞;
 *      · 「我要刺杀 3 号 / 我的刺杀目标是」:刺客的私有决策,公开说出来等于
 *        在桌上明牌(而且刺杀阶段本来就没有公开发言,出现即越界);
 *      · 提示词 / JSON 字段名残留、跳出角色(「作为一个 AI」)。
 *
 * 一句话:**允许骗人、允许跳任何身份,不允许把只有自己知道的事实当公共事实讲**
 * (与狼人杀那句「你可以骗人,但不能编造这个世界发生过什么」同源)。
 *
 * ⚠️ 已知缺口(如实写在这里,不假装没有):
 *    · 「3 号和我都不是坏人」这类**绕一层的自曝**拦不住 —— 代码层判不了语义;
 *    · 「我上一轮投了成功」不拦:它可能是真话(好人),也可能是坏人在装 ——
 *      和「我是忠臣」一样属于声明;
 *    · 引用一条不存在的发言(幻觉)不在这里拦,靠提示词的【引用纪律】约束。
 *
 * 命中之后的处理策略在 agent.js(先带违规说明重试一次 → 仍命中用确定性中性句),
 * 与狼人杀/卧底同一套;这里只负责判「这句话能不能公开说」,不判句子好不好。
 */

/** 自曝坏人阵营:只要和「我」连在一起就判泄漏 */
const EVIL_SELF_RE = [
  /(?:我|俺|咱|自己)\s*(?:就|真|其实|确实|当然)?\s*(?:是|跳|属于)\s*(?:一个|一名|个|只)?\s*(?:坏人|反派|坏蛋|坏阵营|刺客|莫甘娜|莫德雷德|爪牙)/,
  /(?:我们|咱们|俺们)\s*(?:这边|那边|这一边)?\s*(?:就|都|全)?\s*(?:是)?\s*(?:坏人|反派|坏阵营|刺客团)/,
  /(?:我们|咱们|俺们)的?\s*(?:队友|同伴|同伙|刺客|莫甘娜|莫德雷德|爪牙)/,
  /我的\s*(?:坏人)?(?:队友|同伴|同伙)/,
  /(?:我|俺)\s*(?:和|跟)\s*\d+\s*号\s*(?:都|一起)?\s*是\s*(?:坏人|刺客|莫甘娜|莫德雷德|爪牙)/,
];

/**
 * 自曝失败卡。
 * ⚠️ 「我投了**成功**」是**放行**的(好人本来就只能投成功,坏人也可以这么装)——
 *    所以这里只拦「失败/破坏」那一侧,不要写成「我投了…」一概拦。
 */
const FAIL_CARD_RE = [
  /(?:我|俺)\s*(?:这轮|这一轮|刚才|上一轮|刚刚)?\s*(?:投|出|打|交|放)了?\s*(?:一张|一票|个|张)?\s*(?:失败|破坏|黑票|坏票)/,
  /(?:我|俺)\s*(?:这轮|这一轮|刚才)?\s*(?:投的|出的是|打的是)\s*(?:失败|破坏)/,
  /(?:我们|咱们)\s*(?:这轮|这一轮)?\s*(?:投|出|打)了?\s*(?:一张|一票|个|张)?\s*(?:失败|破坏)/,
];

/** 刺客的私有决策(刺杀阶段之外出现即越界) */
const ASSASSIN_RE = [
  /我\s*(?:要|想|准备|打算|决定)?\s*(?:刺杀|暗杀)\s*\d+\s*号/,
  /我的?\s*(?:刺杀|暗杀)\s*(?:目标|对象|人选)/,
  /(?:我|俺)\s*(?:是|就是)\s*(?:那个)?\s*刺客/,
];

/**
 * 把**梅林的私有知识**说成事实。
 * 这是阿瓦隆独有的一条:只有梅林能「知道」谁是坏人,所以「我知道 X 号是坏人」
 * 等于把「我是梅林」四个字说了出来 —— 但它比「我是梅林」更隐蔽、更容易被模型顺手写出来。
 */
const KNOWS_FACT_RE = [
  /我\s*(?:能|可以)?\s*(?:知道|确定|确信|保证|看得到|看到|看清)\s*(?:了)?\s*\d+\s*号\s*(?:就|肯定|一定|百分之百)?\s*(?:是|不是)\s*(?:个|一名)?\s*(?:坏人|好人|刺客|莫甘娜|莫德雷德|爪牙|梅林|派西维尔|忠臣)/,
  /我\s*(?:能|可以)?\s*(?:知道|确定|看到|看清)\s*谁\s*(?:是|才|在)\s*(?:坏人|刺客|莫甘娜|莫德雷德|爪牙)/,
  /(?:坏人|刺客|莫甘娜|莫德雷德|爪牙)\s*(?:就|分别)\s*是\s*\d+\s*号/,
];

/** 跳出角色 / JSON 残留 */
const CODE_RE = /\b(?:thinking|say|vote|reason|json|markdown|prompt|system|action|target|team|card|avalon|merlin|percival|mordred)\b/i;
const META_RE = [
  /作为一个?\s*(?:AI|人工智能|语言模型|助手)/,
  /(?:根据|按照)\s*(?:规则|提示词|设定)\s*第?\s*\d*\s*条?/,
  /我的\s*(?:提示词|系统设定|指令)/,
];

/** 座位号自指:只拦「我是/我坐 X 号」,「X 号说得不对」是正常点名 */
const SELF_SEAT_RE = [
  /我\s*(?:就|是|坐|在)\s*(?:第\s*)?\d+\s*号/,
  /\d+\s*号\s*(?:就)?是我/,
];

/**
 * 中性兜底发言(**确定性**,由座位 + 轮次决定用哪一条)。
 *
 * 三个要求(与狼人杀同一个池子哲学):
 *   ① 不含任何具体信息(不点名、不表态、不提身份)—— 换成任何局面都成立;
 *   ② 确定性:同一局面重跑永远同一句;
 *   ③ 读起来像真人敷衍的一句,而不是报错文案。
 *
 * 这里是一对**队长提名时的说辞**:队长必须说点什么(`say`),空着会很怪。
 */
export const NEUTRAL_SAY = [
  ['我按座位顺序挑了这几位,先看看能不能过。', '不同意就投反对,下一轮换人。'],
  ['这一队我想先试一轮。', '有意见直接投反对票,别憋着。'],
  ['我选人没有别的意思。', '谁觉得不合适就否掉。'],
  ['先把这一轮打过去再说。', '我的理由在票里讲。'],
];

/** 中性投票理由(≤25 字,投票失败时用) */
export const NEUTRAL_REASON = [
  '我先保守一票。',
  '这一队我不太放心。',
  '先看看票型再说。',
  '这轮我按直觉。',
];

/**
 * 确定性地挑一条中性发言。
 * 为什么用 (seat, round) 的哈希而不是 Math.random:同一局重放必须得到同一句话,
 * 否则被拦两次的两段发言会自相矛盾,观众立刻出戏(研究文档「坑 8」)。
 */
export function neutralSay(seat = 0, round = 1) {
  const i = Math.abs((Number(seat) || 0) * 7 + (Number(round) || 1) * 13) % NEUTRAL_SAY.length;
  return NEUTRAL_SAY[i].map((s) => cleanBubble(s, 60));
}

/** 中性投票理由(确定性) */
export function neutralReason(seat = 0, round = 1) {
  const i = Math.abs((Number(seat) || 0) * 5 + (Number(round) || 1) * 11) % NEUTRAL_REASON.length;
  return cleanBubble(NEUTRAL_REASON[i], 25);
}

/** 一条气泡的清洗:压空白、去引号、超长截到最后一个标点(与狼人杀/卧底同一套) */
export function cleanBubble(raw, maxLen = 60) {
  let s = String(raw ?? '');
  s = s.replace(/```[\s\S]*?```/g, ' ');
  s = s.replace(/[\r\n\t]+/g, ' ');
  s = s.replace(/^[\s"'“”‘’「」『』]+|[\s"'“”‘’「」『』]+$/g, '');
  s = s.replace(/\s{2,}/g, ' ');
  if (s.length > maxLen) {
    const head = s.slice(0, maxLen);
    const cut = Math.max(head.lastIndexOf('。'), head.lastIndexOf('，'),
      head.lastIndexOf('、'), head.lastIndexOf('；'), head.lastIndexOf(' '));
    s = cut > maxLen * 0.5 ? head.slice(0, cut) : head;
  }
  return s.trim();
}

/**
 * 判一句公开说法有没有越界。返回 null(干净)或一条命中记录。
 *
 * @param {string} text 已经 cleanBubble 过的那句话
 * @returns {null|{kind:string, hit:string, why:string}}
 */
export function checkSayLeak(text) {
  const s = String(text ?? '');
  if (!s) return null;

  for (const re of EVIL_SELF_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'evil', hit: m[0], why: `说出了自己是坏人阵营 / 点了自己的队友(${m[0]})` };
  }
  for (const re of FAIL_CARD_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'card', hit: m[0], why: `说出了自己投过失败卡(${m[0]})` };
  }
  for (const re of ASSASSIN_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'assassin', hit: m[0], why: `说出了刺杀目标 / 自认刺客(${m[0]})` };
  }
  for (const re of KNOWS_FACT_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'knows', hit: m[0], why: `把只有梅林知道的事说成了事实(${m[0]})` };
  }
  for (const re of META_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'meta', hit: m[0], why: `跳出了角色(${m[0]})` };
  }
  for (const re of SELF_SEAT_RE) {
    const m = re.exec(s);
    if (m) return { kind: 'selfSeat', hit: m[0], why: `用座位号指自己(${m[0]})` };
  }
  const code = CODE_RE.exec(s);
  if (code) return { kind: 'code', hit: code[0], why: `出现了提示词/JSON 字段名(${code[0]})` };
  return null;
}

/**
 * 投票理由的过滤:规则与发言完全一样(也是公开可见的一句话)。
 * 单独一个名字只是为了调用处读起来清楚 —— 实现**必须**共用 checkSayLeak,
 * 否则发言与理由两套规则迟早漂移(这个仓库「两条路径各写一份」栽过两次)。
 */
export function checkReasonLeak(reason) {
  return checkSayLeak(reason);
}

/** 整段发言(多条气泡)一起判:任何一条命中就算命中 */
export function checkSpeechLeak(bubbles) {
  for (const b of (Array.isArray(bubbles) ? bubbles : [bubbles])) {
    const leak = checkSayLeak(b);
    if (leak) return { ...leak, bubble: String(b) };
  }
  return null;
}

/** 被拦掉之后给模型的修复要求(重试那一次拼进 user 消息) */
export function repairHint(leak) {
  if (!leak) return '';
  const map = {
    evil: '你说出了自己属于坏人阵营、或者点了自己的同伴 —— 这是自曝,不是声明。'
      + '你要么彻底不提「我们/队友」这类说法,要么把自己当成好人来发言。'
      + '(注意:跳任何身份都是允许的**声明**,只有「我是坏人」「我队友」这类才是犯规。)',
    card: '你说出了自己投过失败卡。好人按规则只能投成功,所以这句话等于宣布自己是坏人。'
      + '如果你要表态,可以说「我这张卡是干净的」——那是声明,别人信不信是另一回事。',
    assassin: '你说出了刺客的私有决策(刺杀目标 / 自认刺客)。这些只有你自己知道,公开说出来就是把牌摊开。',
    knows: '你把「我知道谁是坏人」说成了事实 —— 整个桌上只有梅林有这份信息,'
      + '这句话等于当众报出「我是梅林」。改成「我怀疑 / 我认为 / 我倾向于」,那是推理,可以放心说。',
    meta: '你跳出了角色。你在牌桌上,不是裁判、不是解说、不是 AI 助手。删掉这类话。',
    selfSeat: '你用座位号指了自己。请用「我」,不要报座位号。',
    code: '你的话里混进了 JSON 字段名 / 英文标识。请只输出像真人在桌边说的话。',
  };
  return map[leak.kind] || '这句话不能公开说,请重写。';
}
