/**
 * 「谁是卧底」词库 —— 人工筛过的**成对**词。
 *
 * 每一对方是 { 平民词, 卧底词 }:所有平民拿同一个词,卧底拿另一个相近但不同的词。
 *
 * ────────────────────────────────────────────────────────────────
 * 为什么必须人工筛、不能拿现成的近义词库自动生成
 *
 * 研究文档(docs/GAMES-RESEARCH.md 的「谁是卧底 · 已知的坑」第 8 条)把
 * 「词对太难/太易」列成头号平衡问题:
 *   · 两个词**太近**(「番茄 / 西红柿」)→ 描述几乎重合,谁也投不出去,四轮下来僵局;
 *   · 两个词**太远**(「牛奶 / 螺丝刀」)→ 第一轮就露馅,卧底零操作空间。
 * 自动生成的近义词对几乎全落在「太近」那一端(同义词),所以这里一个一个挑:
 * 每对都是「同一类、但不是同一个东西,而且描述起来会自然撞车」的程度。
 *
 * difficulty 的口径(与 gameDefaults.mjs 的 difficulty 对应):
 *   1 = 差别明显(easy:先说的人一两句就能锚定,卧底很快被逼到墙角)
 *   2 = 同一类目下的两样东西(normal:最常见的那种局)
 *   3 = 近义/上下位/强关联(hard:只差一点点,最难投)
 *
 * ⚠️ 词库只进「裁判」那一侧:发词由 kernel 做,**绝不出现在任何 AI 的提示词里**
 *    (测试 tools/undercovertest.mjs 有一条断言盯着「prompt 里只有自己的词」)。
 *    所以这个文件可以被任何地方 import 也不构成泄漏 —— 但它除了发词之外不该被
 *    别的模块拿去拼提示词。
 */

