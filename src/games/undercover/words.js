/** 词库里一共多少对(测试与界面用它,不要在别处写死数字) */
export const WORD_PAIR_COUNT = WORD_PAIRS.length;

/**
 * 难度名 → 允许的 difficulty 档位(含)。
 *
 * 为什么用范围而不是等值:easy 只有 16 对,单纯按 1 档抽会让同一局反复抽到
 * 同样的几对;range 让每个档位都有足够的池子。
 */
const DIFFICULTY_RANGE = {
  easy: [1, 1],
  normal: [1, 2],
  hard: [2, 3],
};

/**
 * 从词库里挑一对。
 *
 * ⚠️ 随机源是**注入**的(rand() → [0,1)),不用 Math.random 直接抽:
 *    测试与截图工具要能「同一局重跑出同样的词」,否则失败无法复现;
 *    kernel 默认用 Math.random(真随机),测试传一个种子随机源即可。
 * @param {{difficulty?:string, rand?:()=>number, exclude?:string[]}} [opts]
 *   exclude:已经用过的词(连续两局不重复) —— 可选,只比较平民词
 * @returns {WordPair} 一定会返回一对;池子空了就退回整个词库
 */
export function pickWordPair({ difficulty = 'normal', rand = Math.random, exclude = [] } = {}) {
  const [lo, hi] = DIFFICULTY_RANGE[String(difficulty)] || DIFFICULTY_RANGE.normal;
  const used = new Set(exclude.filter(Boolean));
  let pool = WORD_PAIRS.filter((p) => p.d >= lo && p.d <= hi && !used.has(p.c));
  if (!pool.length) pool = WORD_PAIRS.filter((p) => p.d >= lo && p.d <= hi);
  if (!pool.length) pool = WORD_PAIRS.slice();
  const i = Math.min(pool.length - 1, Math.max(0, Math.floor((rand() || 0) * pool.length)));
  return pool[i];
}
