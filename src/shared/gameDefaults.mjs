/**
 * 某个游戏的默认设置(**深拷贝**,调用方可以放心改)。
 *
 * 认不出的 gameId 给空对象,不做「回落到 poker 默认值」那种兜底 ——
 * 给一个不存在的游戏套上扑克的盲注,只会把拼写错误藏起来。
 */
export function gameDefaultsOf(gameId = DEFAULT_GAME_ID) {
  const d = GAME_DEFAULTS[gameId];
  return d ? JSON.parse(JSON.stringify(d)) : {};
}

/**
 * 所有游戏的默认设置(深拷贝)。DEFAULT_CONFIG.games 用它 ——
 * 以后在 GAME_DEFAULTS 里加一个游戏,两端默认配置自动多出那一个 key。
 *
 * 为什么必须拷贝:默认配置是**可写模板**(deepMerge / config:set 会往上叠补丁),
 * 直接把真源里的对象挂上去,一次「读默认值再改」就会污染真源,
 * 后面所有读到默认值的地方都跟着变(而且只在同一进程里复现,最难查)。
 */
export function gameDefaultsAll() {
  return JSON.parse(JSON.stringify(GAME_DEFAULTS));
}

/**
 * 读某个游戏的配置 —— **唯一入口**。
 *
 * 为什么要有这个 helper:凡是读游戏设置的地方都写 `cfg.games.poker.x` 的话,
 * 二期加游戏、换默认游戏时就得全仓改一遍;收敛到一处之后,加新游戏只要把
 * gameId 一路传下去。(读 global 不需要 helper:那一层是扁平的,而且就是全局的。)
 *
 * 返回值是**只读引用**(不拷贝):调用方多、每帧都可能读,拷一份纯属浪费。
 * 但要改配置,一律走 saveConfig/collect 那条写路径,别原地改这个对象。
 */
export function gameCfg(cfg, gameId = DEFAULT_GAME_ID) {
  const g = cfg?.games?.[gameId];
  return (g && typeof g === 'object' && !Array.isArray(g)) ? g : {};
}
