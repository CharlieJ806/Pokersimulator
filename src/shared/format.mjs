/**
 * 数字显示的小工具 —— 桌面 / 手机、荷官 / 玩家、任何游戏都用同一套写法。
 *
 * 为什么单独一个文件:
 *   一开始它写在 3D 屏幕模块里(只有界面用它),于是平台壳(app.js)为了
 *   打一行「平均筹码 1.2k」就得 import 整个扑克屏幕模块 —— 而 2b 之后
 *   屏幕是由游戏自己 mount 的,壳不该再认识它。搬到 shared 之后,
 *   任何游戏/任何面板都能用同一份格式化规则。
 *
 * 规则(别小看这两行,牌桌上一半的数字都过它):
 *   · 一万以下照原样显示,不加千分位(牌桌上 2,000 比 2000 更占地方);
 *   · 一万以上缩成 1.2k / 12k(手机上一行要塞下「存活 6/6 · 平均筹码 1.2k」);
 *   · 整数千位不带小数点(10000 → 10k,而不是 10.0k)。
 */

export function fmt(n) {
  const v = Math.round(n || 0);
  if (Math.abs(v) >= 10000) return (v / 1000).toFixed(v % 1000 === 0 ? 0 : 1) + 'k';
  return String(v);
}
